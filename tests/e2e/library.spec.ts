import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const password = () => process.env.E2E_ADMIN_PASSWORD || readFileSync('.dev.vars', 'utf8').match(/^ADMIN_PASSWORD=(.*)$/m)?.[1]?.trim()
test('capture, mixed collections, handoff, explicit publication and private edits', async ({ page, context }) => {
  expect((await context.request.post('/api/admin/login', {data:{password:password()}})).status()).toBe(200)
  await context.grantPermissions(['clipboard-read','clipboard-write'])
  const marker = `资料验收 ${crypto.randomUUID().slice(0,8)}`
  async function action(data: unknown) { const response=await context.request.post('/api/admin/library',{data}); expect(response.status()).toBe(200); return response.json() }
  await page.goto('/admin/library')
  await page.getByRole('button',{name:'手动收录',exact:true}).click()
  await page.getByLabel('标题',{exact:true}).fill(marker)
  await page.getByLabel('正文或要点').fill('## 原始笔记\n\nPRIVATE_CONTEXT\n\n- 要点一\n- 要点二')
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/admin/library') && r.request().method()==='POST')
  await page.getByRole('button',{name:'保存到资料库'}).click()
  const note=(await (await saved).json()).item
  await expect(page.getByRole('region',{name:'内容详情'}).getByRole('heading',{name:marker,exact:true})).toBeVisible()
  const collection=await action({action:'collection',title:marker,description:'A topic, not a task'})
  const tool=await action({action:'capture',input:{request_key:crypto.randomUUID(),type:'tool',title:marker+' 工具',content:'PRIVATE_TOOL',summary:'工具用途',source_url:'https://example.com/'+crypto.randomUUID(),collection_ids:[collection.id],topics:['验收']}})
  // Collection revisions are part of the UI's server-loaded context.
  await page.reload()
  await page.getByRole('button',{name:'属性',exact:true}).click()
  await page.getByRole('checkbox',{name:marker,exact:true}).click()
  await expect(page.getByRole('checkbox',{name:marker,exact:true})).toBeChecked()
  await page.getByRole('button',{name:'关闭属性',exact:true}).click()
  await page.goto('/admin/library?collection='+collection.id)
  await expect(page.getByRole('region',{name:'资料列表'}).getByRole('heading',{name:marker,exact:true})).toBeVisible()
  await page.getByRole('checkbox',{name:'选择 '+marker,exact:true}).check()
  await page.getByRole('checkbox',{name:'选择 '+marker+' 工具',exact:true}).check()
  await page.getByRole('button',{name:'复制给助手',exact:true}).click()
  await page.getByLabel('你想继续做什么？').fill('根据这些资料写一份比较')
  await page.getByRole('dialog',{name:'复制给助手'}).getByRole('button',{name:'复制给助手',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'复制给助手'}).getByRole('status')).toContainText('已复制内容')
  const clipboard=await page.evaluate(()=>navigator.clipboard.readText())
  for(const value of ['PRIVATE_CONTEXT','PRIVATE_TOOL',note.id,tool.item.id,tool.item.source_url,'根据这些资料写一份比较']) expect(clipboard).toContain(value)
  await page.goto(tool.href)
  await page.getByRole('button',{name:'更多操作',exact:true}).click()
  await page.getByRole('menuitem',{name:'编辑公开版本',exact:true}).click()
  await page.getByLabel('公开标题',{exact:true}).fill(marker+' 公开工具')
  await page.getByLabel('公开介绍',{exact:true}).fill('REVIEWED_PUBLIC')
  await page.getByRole('button',{name:'确认发布这个版本',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'编辑公开版本'})).toHaveCount(0)
  await page.getByRole('button',{name:'编辑',exact:true}).click()
  await page.getByRole('textbox',{name:'资料正文编辑器'}).fill('PRIVATE_AFTER_PUBLICATION')
  await page.getByRole('button',{name:'完成编辑',exact:true}).click()
  await expect(page.locator('.library-prose')).toContainText('PRIVATE_AFTER_PUBLICATION')
  const publicHtml=await (await context.request.get('/tools')).text()
  expect(publicHtml).toContain('REVIEWED_PUBLIC')
  expect(publicHtml).not.toContain('PRIVATE_AFTER_PUBLICATION')
  expect(publicHtml).not.toContain('PRIVATE_TOOL')
  await page.goto('/admin/library?q='+encodeURIComponent(marker))
  await expect(page.getByRole('region',{name:'资料列表'}).getByRole('heading',{name:marker,exact:true})).toBeVisible()
  await page.goto(tool.href)
  await page.getByRole('button',{name:'更多操作',exact:true}).click()
  await page.getByRole('menuitem',{name:'编辑公开版本',exact:true}).click()
  await page.getByRole('button',{name:'撤回公开',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'编辑公开版本'})).toHaveCount(0)
  expect(await (await context.request.get('/tools')).text()).not.toContain('REVIEWED_PUBLIC')
})

test('public and private layouts fit desktop and phone, theme persists, unavailable source is truthful',async({page,context})=>{
  expect((await context.request.post('/api/admin/login',{data:{password:password()}})).status()).toBe(200)
  const response=await context.request.post('/api/admin/library',{data:{action:'capture',input:{request_key:crypto.randomUUID(),type:'article',title:'无法读取的原文',source_url:'https://example.com/unavailable-'+crypto.randomUUID(),source_status:'unavailable'}}})
  expect(response.status()).toBe(200)
  const {href}=await response.json()
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:900})
    for(const path of ['/', '/work', '/writing', '/tools', '/prompts', '/about','/admin','/admin/collections','/admin/publish','/admin/studio','/admin/tools','/admin/prompts','/admin/settings', href]){
      await page.goto(path)
      await expect(page.locator('body')).not.toContainText('Application error')
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width} ${path}`).toBe(true)
      if(path==='/'||path==='/admin'||path===href) await page.screenshot({path:`/tmp/studio-${path==='/'?'home':path==='/admin'?'admin':'reader'}-${width}.png`,fullPage:true})
    }
    await expect(page.getByText('原文尚未成功读取。当前仅保留已知信息与来源链接。')).toBeVisible()
  }
  await page.goto('/')
  const dark=page.getByRole('button',{name:'切换到晚上模式'})
  if(await dark.count()) await dark.click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-color-mode','dark')
  await page.screenshot({path:'/tmp/studio-home-dark.png',fullPage:true})
})

test('long Markdown stays readable and copyable on a phone',async({page,context})=>{
  expect((await context.request.post('/api/admin/login',{data:{password:password()}})).status()).toBe(200)
  await context.grantPermissions(['clipboard-read','clipboard-write'])
  const content=['## 长文笔记', '- 保留结构与来源', '```ts', 'const longValue = "'+ 'a'.repeat(500) +'"', '```', ...Array.from({length:30},(_,i)=>`### 观点 ${i+1}\n\n${'这是用于验证长内容阅读和复制的本地资料。'.repeat(12)}`)].join('\n\n')
  const response=await context.request.post('/api/admin/library',{data:{action:'capture',input:{request_key:crypto.randomUUID(),type:'note',title:'长内容验收',content}}})
  expect(response.status()).toBe(200);const {href}=await response.json()
  await page.setViewportSize({width:390,height:844});await page.goto(href)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.getByRole('button',{name:'复制正文',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'已复制正文'})).toBeVisible()
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(content)
  await expect(page.getByRole('heading',{name:'观点 30',exact:true})).toBeAttached()
})
